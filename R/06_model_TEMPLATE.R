IMPUTE_LINE <- "L1"           # L1 不插补 / L2 中位数 / L3 条件均值 / L4 PMM

# ---- 模型 -------------------------------------------------------------------
# 从 R/lib_models.R 的工厂里挑一个，括号里可以覆盖默认参数：
#
#   make_xgb()                         默认参数
#   make_xgb(list(eta = 0.03))         改学习率
#   make_lgb(list(num_leaves = 127L))  lightgbm
#   make_ranger(num_trees = 300L)      随机森林（不支持 NA，L1 不可用）
#   make_glmnet(alpha = 1)             lasso（不支持 NA，L1 不可用）
#
fit_predict <- make_xgb()

