# =============================================================================
# 06_model_TEMPLATE.R —— 建模模板
#
# 【怎么用】
#   1. 复制本文件，改名为 R/06_model_<线号>_<模型名>.R
#   2. 改下面三个配置变量和 fit_predict 那一行
#   3. 跑：Rscript R/06_model_<你的文件>.R
#   4. 检查 output/oof/ 下有没有生成你的文件，然后提交
#
# 【框架做了什么，为什么你不用管】
#   R/06_framework.R 里写死了两条纪律，它们保证所有人的分数可比：
#
#   1. 插补器只在训练折上拟合，绝不碰验证折
#      否则验证折的信息会通过插补参数渗进训练，CV 分数虚高，
#      而且虚高幅度随插补复杂度递增 —— 会系统性地偏袒复杂方法，
#      让整个对比实验失去意义。
#
#   2. 派生特征在插补之后才算
#      比值和差值型特征只要任一分量是 NA 就会传播成 NA，
#      插补前算等于白算。
#
#   早停所需的内部验证集由 fit_predict 自己从训练折里再切 20%
#   （见 R/lib_models.R），外层验证折从头到尾不参与任何模型选择。
#
# 【可选配置】
#   USE_DERIVED <- FALSE   不计算 6 个派生特征
#                          （消融已证明它们无效，见项目说明 6.6）
#   TIER        <- "B"     全量 69 万行，产出 test 预测供集成使用
# =============================================================================

source("R/lib_models.R")

