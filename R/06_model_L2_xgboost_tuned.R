# 06_model_L2_xgboost_tuned.R —— L2 × xgboost（调参版）
#
# 与 06_model_L2_xgboost.R 的唯一区别：使用 R/10_tune.R 搜出的最优参数。
#
# 为什么要另立文件而不是直接改原来那个：
#   4x4 实验网格是一个**受控对比实验** —— 十四个格子必须用同一套超参数，
#   否则「L1 比 L3 好」到底是插补的功劳还是参数的功劳就分不清了。
#   所以网格保持默认参数不动，调参版本作为**面向提交**的独立候选存在。
#
# 调参结果（18 组，3 折 20 万行，见 output/tune_xgboost.rds）：
#   默认 eta=0.05 depth=6   0.96078
#   最优 eta=0.05 depth=4   0.96145   (+0.00066)
#
# 更浅的树更好，这与发现 5（标签几乎是少数几个特征的单调函数）自洽 ——
# 不需要很深的树去拟合复杂交互。
# =============================================================================

